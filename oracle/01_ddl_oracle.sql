-- 01_ddl_oracle.sql
-- Banco de Dados: Oracle
-- Atende aos Critérios: 7 Entidades, Estados Claros na Reserva e Tabela Associativa N:M.

CREATE TABLE Hospede (
    id_hospede NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR2(11) UNIQUE NOT NULL,
    nome_completo VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    telefone VARCHAR2(20),
    data_cadastro DATE DEFAULT SYSDATE
);

CREATE TABLE Categoria_Quarto (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_categoria VARCHAR2(50) NOT NULL,
    capacidade_maxima NUMBER NOT NULL CHECK (capacidade_maxima > 0),
    valor_diaria_base NUMBER(10,2) NOT NULL CHECK (valor_diaria_base > 0)
);

CREATE TABLE Quarto (
    id_quarto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria NUMBER NOT NULL,
    numero_quarto VARCHAR2(10) UNIQUE NOT NULL,
    andar NUMBER,
    status_manutencao NUMBER(1) DEFAULT 0 CHECK (status_manutencao IN (0, 1)),
    CONSTRAINT fk_quarto_categoria FOREIGN KEY (id_categoria) REFERENCES Categoria_Quarto(id_categoria)
);

CREATE TABLE Reserva (
    id_reserva NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hospede NUMBER NOT NULL,
    id_quarto NUMBER NOT NULL,
    data_reserva TIMESTAMP DEFAULT SYSTIMESTAMP,
    data_entrada_prevista DATE NOT NULL,
    data_saida_prevista DATE NOT NULL,
    data_checkin_real TIMESTAMP,
    data_checkout_real TIMESTAMP,
    status_reserva VARCHAR2(20) DEFAULT 'PENDENTE' CHECK (status_reserva IN ('PENDENTE', 'CONFIRMADA', 'CHECK-IN', 'CHECK-OUT', 'CANCELADA', 'NO-SHOW')),
    valor_total_bruto NUMBER(10,2) NOT NULL,
    percentual_desconto NUMBER(5,2) DEFAULT 0,
    valor_final_pago NUMBER(10,2),
    CONSTRAINT fk_reserva_hospede FOREIGN KEY (id_hospede) REFERENCES Hospede(id_hospede),
    CONSTRAINT fk_reserva_quarto FOREIGN KEY (id_quarto) REFERENCES Quarto(id_quarto),
    CONSTRAINT chk_datas_reserva CHECK (data_saida_prevista > data_entrada_prevista)
);

CREATE TABLE Cancelamento (
    id_cancelamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva NUMBER UNIQUE NOT NULL,
    data_cancelamento TIMESTAMP DEFAULT SYSTIMESTAMP,
    taxa_multa_aplicada NUMBER(10,2) NOT NULL,
    motivo_cancelamento VARCHAR2(255),
    CONSTRAINT fk_cancelamento_reserva FOREIGN KEY (id_reserva) REFERENCES Reserva(id_reserva) ON DELETE CASCADE
);

-- RESOLUÇÃO N:M (Reserva x Serviços Consumidos)
CREATE TABLE Servico (
    id_servico NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_servico VARCHAR2(100) NOT NULL,
    valor_unitario NUMBER(10,2) NOT NULL CHECK (valor_unitario >= 0)
);

CREATE TABLE Consumo_Servico (
    id_consumo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva NUMBER NOT NULL,
    id_servico NUMBER NOT NULL,
    quantidade NUMBER NOT NULL CHECK (quantidade > 0),
    data_consumo TIMESTAMP DEFAULT SYSTIMESTAMP,
    valor_total_item NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_consumo_reserva FOREIGN KEY (id_reserva) REFERENCES Reserva(id_reserva) ON DELETE CASCADE,
    CONSTRAINT fk_consumo_servico FOREIGN KEY (id_servico) REFERENCES Servico(id_servico)
);
